from colorama import Fore, Style, init

init(autoreset=True)

def print_terminal_report(url, score, results):
    """Prints a colored security report to the terminal."""
    print(f"\n{Style.BRIGHT}Security Analysis for: {url}")
    print("=" * 60)

    # Score Display
    score_color = Fore.GREEN if score >= 80 else Fore.YELLOW if score >= 50 else Fore.RED
    print(f"Overall Security Score: {score_color}{score}%")
    print("-" * 60)

    for header, data in results.items():
        status = f"{Fore.GREEN}[PASS]" if data["secure"] else f"{Fore.RED}[FAIL]"
        print(f"{status} {Style.BRIGHT}{header}")
        print(f"    Value: {data['value'] if data['value'] else 'Not set'}")
        print(f"    Description: {data['description']}")
        if not data["secure"]:
            print(f"    {Fore.YELLOW}Recommendation: {data['recommendation']}")
        print("-" * 60)

def save_markdown_report(url, score, results, filename="report.md"):
    """Saves the analysis results to a Markdown file."""
    with open(filename, "w") as f:
        f.write(f"# Web Security Header Analysis Report\n\n")
        f.write(f"**Target URL:** {url}  \n")
        f.write(f"**Overall Security Score:** {score}%\n\n")
        f.write(f"## Detailed Findings\n\n")
        f.write(f"| Header | Status | Value | Recommendation |\n")
        f.write(f"| :--- | :--- | :--- | :--- |\n")

        for header, data in results.items():
            status = "✅ Pass" if data["secure"] else "❌ Fail"
            val = data["value"] if data["value"] else "None"
            rec = data["recommendation"]
            f.write(f"| {header} | {status} | `{val}` | {rec} |\n")

        f.write(f"\n\n---\n*Generated by Web Security Header Analyzer*")
